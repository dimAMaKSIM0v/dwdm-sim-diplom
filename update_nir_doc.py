# Helpers

def delete_paragraph(paragraph):
    p = paragraph._element
    p.getparent().remove(p)
    paragraph._p = paragraph._element = None


def heading1_paragraphs():
    return [p for p in doc.paragraphs if p.style.name == 'Heading 1']


def index_of_paragraph(paragraph):
    el = paragraph._element
    for i, p in enumerate(doc.paragraphs):
        if p._element is el:
            return i
    return -1


def clear_section_by_heading_paragraph(heading_paragraph):
    idx = index_of_paragraph(heading_paragraph)
    if idx < 0:
        raise ValueError('Heading paragraph not found in document')
    i = idx + 1
    while i < len(doc.paragraphs):
        if doc.paragraphs[i].style.name == 'Heading 1':
            break
        delete_paragraph(doc.paragraphs[i])
    return heading_paragraph


def insert_paragraph_after(paragraph, text='', style=None):
    new_p = OxmlElement('w:p')
    paragraph._element.addnext(new_p)
    new_par = Paragraph(new_p, paragraph._parent)
    if style:
        new_par.style = style
    if text:
        new_par.add_run(text)
    return new_par


def insert_paragraph_after_element(element, parent, text='', style=None):
    new_p = OxmlElement('w:p')
    element.addnext(new_p)
    new_par = Paragraph(new_p, parent)
    if style:
        new_par.style = style
    if text:
        new_par.add_run(text)
    return new_par


def insert_table_after(paragraph, rows, cols, style=None):
    tbl = doc.add_table(rows=rows, cols=cols)
    if style:
        tbl.style = style
    paragraph._element.addnext(tbl._element)
    return tbl


def insert_picture_after(paragraph, image_path, width_cm=None):
    p = insert_paragraph_after(paragraph, '')
    run = p.add_run()
    if width_cm:
        run.add_picture(str(image_path), width=Cm(width_cm))
    else:
        run.add_picture(str(image_path))
    return p


def add_paragraphs_after(heading_paragraph, items):
    current = heading_paragraph
    for item in items:
        kind = item[0]
        if kind == 'p':
            _, text, style = item
            current = insert_paragraph_after(current, text, style)
        elif kind == 'img':
            _, img_path, width_cm, caption_text = item
            img_p = insert_picture_after(current, img_path, width_cm=width_cm)
            cap_p = insert_paragraph_after(img_p, caption_text, None)
            current = cap_p
        elif kind == 'table':
            _, table_data, caption_text = item
            rows = len(table_data)
            cols = len(table_data[0]) if rows else 0
            tbl = insert_table_after(current, rows, cols, style='Table Grid')
            for r in range(rows):
                for c in range(cols):
                    tbl.cell(r, c).text = str(table_data[r][c])
            cap_p = insert_paragraph_after_element(tbl._element, current._parent, caption_text, None)
            current = cap_p
        else:
            raise ValueError('Unknown item kind')
    return current

